def beds_per_thousand_elderly(year: int) -> Optional[float]:
    """派生指标：每千名 65 岁及以上老年人拥有的养老床位数（张/千人）。
    计算式 = 当年养老床位总数(万张) × 10000 ÷ 当年 65+ 人口(万人) × 1000
    """
    bed = next((r["beds"] for r in ELDERCARE if r["year"] == year), None)
    pop = next((r["pop65"] for r in ELDERLY_TREND if r["year"] == year and r["pop65"]), None)
    if bed is None or pop is None:
        return None
    return round(bed * 10000 / (pop * 10000) * 1000, 1)


def project_pct65(end_year: int = 2035) -> List[Dict]:
    """【作品自建外推，非官方预测】
    以 2015—2024 年 65+ 占比序列拟合一元线性回归，外推至 end_year。
    仅用于呈现"若维持近十年增速"的示意情景，不构成官方预测结论。
    """
    pts = [(r["year"], r["pct65"]) for r in ELDERLY_TREND if r["pct65"] is not None and r["year"] >= 2015]
    n = len(pts)
    sx = sum(x for x, _ in pts)
    sy = sum(y for _, y in pts)
    sxy = sum(x * y for x, y in pts)
    sxx = sum(x * x for x, _ in pts)
    slope = (n * sxy - sx * sy) / (n * sxx - sx * sx)
    intercept = (sy - slope * sx) / n

    out = [{"year": y, "pct65": round(v, 2), "kind": "实际"} for y, v in pts]
    for y in range(pts[-1][0] + 1, end_year + 1):
        out.append({"year": y, "pct65": round(slope * y + intercept, 2), "kind": "外推"})
    return out


